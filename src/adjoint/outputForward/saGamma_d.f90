            ff(2, j) = scratch(i, j, k, idvt+1)*rblank
            bb(:, j) = bb(:, j)*rblank
            dd(:, j) = dd(:, j)*rblank
          end do
          call tdia2x2(2_inttype, jl, bb, cc, dd, ff)
          do j=2,jl
            scratch(i, j, k, idvt) = qq(i, j, k, 1, 1)*ff(1, j) + qq(i, &
&             j, k, 1, 2)*ff(2, j)
            scratch(i, j, k, idvt+1) = qq(i, j, k, 2, 1)*ff(1, j) + qq(i&
&             , j, k, 2, 2)*ff(2, j)
          end do
        end do
      end do
! ---------------- i-direction ----------------
      do k=2,kl
        do j=2,jl
          do i=2,il
            voli = one/vol(i, j, k)
            volmi = two/(vol(i, j, k)+vol(i-1, j, k))
            volpi = two/(vol(i, j, k)+vol(i+1, j, k))
            xm = si(i-1, j, k, 1)*volmi
            ym = si(i-1, j, k, 2)*volmi
            zm = si(i-1, j, k, 3)*volmi
            xp = si(i, j, k, 1)*volpi
            yp = si(i, j, k, 2)*volpi
            zp = si(i, j, k, 3)*volpi
            xa = half*(si(i, j, k, 1)+si(i-1, j, k, 1))*voli
            ya = half*(si(i, j, k, 2)+si(i-1, j, k, 2))*voli
            za = half*(si(i, j, k, 3)+si(i-1, j, k, 3))*voli
            ttm = xm*xa + ym*ya + zm*za
            ttp = xp*xa + yp*ya + zp*za
            cnud = -(rsacb2*w(i, j, k, itu1)*cb3inv)
            cam = ttm*cnud
            cap = ttp*cnud
            nutm = half*(w(i-1, j, k, itu1)+w(i, j, k, itu1))
            nutp = half*(w(i+1, j, k, itu1)+w(i, j, k, itu1))
            nu = rlv(i, j, k)/w(i, j, k, irho)
            nutilde = w(i, j, k, itu1)
            chi = nutilde/nu
            chi3 = chi*chi*chi
            fv1 = chi3/(chi3+cv13)
            nut = nutilde*fv1
            nu_m = rlv(i-1, j, k)/w(i-1, j, k, irho)
            nutilde_m = w(i-1, j, k, itu1)
            chi_m = nutilde_m/nu_m
            chi3_m = chi_m*chi_m*chi_m
            fv1_m = chi3_m/(chi3_m+cv13)
            nut_m = nutilde_m*fv1_m
            nu_p = rlv(i+1, j, k)/w(i+1, j, k, irho)
            nutilde_p = w(i+1, j, k, itu1)
            chi_p = nutilde_p/nu_p
            chi3_p = chi_p*chi_p*chi_p
            fv1_p = chi3_p/(chi3_p+cv13)
            nut_p = nutilde_p*fv1_p
            num_v = half*(nu_m+nu)
            nup_v = half*(nu_p+nu)
            nu_tm = half*(nut_m+nut)
            nu_tp = half*(nut_p+nut)
            cdm = (num_v+(one+rsacb2)*nutm)*ttm*cb3inv
            cdp = (nup_v+(one+rsacb2)*nutp)*ttp*cb3inv
            cdm_gamma = (num_v+nu_tm/sigmaf)*ttm
            cdp_gamma = (nup_v+nu_tp/sigmaf)*ttp
            if (cdm + cam .lt. zero) then
              c1m = zero
            else
              c1m = cdm + cam
            end if
            if (cdp + cap .lt. zero) then
              c1p = zero
            else
              c1p = cdp + cap
            end if
            if (cdm_gamma .lt. zero) then
              c2m = zero
            else
              c2m = cdm_gamma
            end if
            if (cdp_gamma .lt. zero) then
              c2p = zero
            else
              c2p = cdp_gamma
            end if
            bb(1, i) = -c1m
            dd(1, i) = -c1p
            bb(2, i) = -c2m
            dd(2, i) = -c2p
            if (addgridvelocities) qs = half*(sfacei(i, j, k)+sfacei(i-1&
&               , j, k))*voli
            uu = xa*w(i, j, k, ivx) + ya*w(i, j, k, ivy) + za*w(i, j, k&
&             , ivz) - qs
            um = zero
            up = zero
            if (uu .lt. zero) um = uu
            if (uu .gt. zero) up = uu
            bb(1, i) = bb(1, i) - up
            dd(1, i) = dd(1, i) + um
            bb(2, i) = bb(2, i) - up
            dd(2, i) = dd(2, i) + um
            rblank = real(iblank(i, j, k), realtype)
            cc(1, 1, i) = qq(i, j, k, 1, 1)
            cc(1, 2, i) = qq(i, j, k, 1, 2)*rblank
            cc(2, 1, i) = qq(i, j, k, 2, 1)*rblank
            cc(2, 2, i) = qq(i, j, k, 2, 2)
            ff(1, i) = scratch(i, j, k, idvt)*rblank
            ff(2, i) = scratch(i, j, k, idvt+1)*rblank
            bb(:, i) = bb(:, i)*rblank
            dd(:, i) = dd(:, i)*rblank
          end do
          call tdia2x2(2_inttype, il, bb, cc, dd, ff)
          do i=2,il
            scratch(i, j, k, idvt) = qq(i, j, k, 1, 1)*ff(1, i) + qq(i, &
&             j, k, 1, 2)*ff(2, i)
            scratch(i, j, k, idvt+1) = qq(i, j, k, 2, 1)*ff(1, i) + qq(i&
&             , j, k, 2, 2)*ff(2, i)
          end do
        end do
      end do
! ---------------- k-direction ----------------
      do j=2,jl
        do i=2,il
          do k=2,kl
            voli = one/vol(i, j, k)
            volmi = two/(vol(i, j, k)+vol(i, j, k-1))
            volpi = two/(vol(i, j, k)+vol(i, j, k+1))
            xm = sk(i, j, k-1, 1)*volmi
            ym = sk(i, j, k-1, 2)*volmi
            zm = sk(i, j, k-1, 3)*volmi
            xp = sk(i, j, k, 1)*volpi
            yp = sk(i, j, k, 2)*volpi
            zp = sk(i, j, k, 3)*volpi
            xa = half*(sk(i, j, k, 1)+sk(i, j, k-1, 1))*voli
            ya = half*(sk(i, j, k, 2)+sk(i, j, k-1, 2))*voli
            za = half*(sk(i, j, k, 3)+sk(i, j, k-1, 3))*voli
            ttm = xm*xa + ym*ya + zm*za
            ttp = xp*xa + yp*ya + zp*za
            cnud = -(rsacb2*w(i, j, k, itu1)*cb3inv)
            cam = ttm*cnud
            cap = ttp*cnud
            nutm = half*(w(i, j, k-1, itu1)+w(i, j, k, itu1))
            nutp = half*(w(i, j, k+1, itu1)+w(i, j, k, itu1))
            nu = rlv(i, j, k)/w(i, j, k, irho)
            nutilde = w(i, j, k, itu1)
            chi = nutilde/nu
            chi3 = chi*chi*chi
            fv1 = chi3/(chi3+cv13)
            nut = nutilde*fv1
            nu_m = rlv(i, j, k-1)/w(i, j, k-1, irho)
            nutilde_m = w(i, j, k-1, itu1)
            chi_m = nutilde_m/nu_m
            chi3_m = chi_m*chi_m*chi_m
            fv1_m = chi3_m/(chi3_m+cv13)
            nut_m = nutilde_m*fv1_m
            nu_p = rlv(i, j, k+1)/w(i, j, k+1, irho)
            nutilde_p = w(i, j, k+1, itu1)
            chi_p = nutilde_p/nu_p
            chi3_p = chi_p*chi_p*chi_p
            fv1_p = chi3_p/(chi3_p+cv13)
            nut_p = nutilde_p*fv1_p
            num_v = half*(nu_m+nu)
            nup_v = half*(nu_p+nu)
            nu_tm = half*(nut_m+nut)
            nu_tp = half*(nut_p+nut)
            cdm = (num_v+(one+rsacb2)*nutm)*ttm*cb3inv
            cdp = (nup_v+(one+rsacb2)*nutp)*ttp*cb3inv
            cdm_gamma = (num_v+nu_tm/sigmaf)*ttm
            cdp_gamma = (nup_v+nu_tp/sigmaf)*ttp
            if (cdm + cam .lt. zero) then
              c1m = zero
            else
              c1m = cdm + cam
            end if
            if (cdp + cap .lt. zero) then
              c1p = zero
            else
              c1p = cdp + cap
            end if
            if (cdm_gamma .lt. zero) then
              c2m = zero
            else
              c2m = cdm_gamma
            end if
            if (cdp_gamma .lt. zero) then
              c2p = zero
            else
              c2p = cdp_gamma
            end if
            bb(1, k) = -c1m
            dd(1, k) = -c1p
            bb(2, k) = -c2m
            dd(2, k) = -c2p
            if (addgridvelocities) qs = half*(sfacek(i, j, k)+sfacek(i, &
&               j, k-1))*voli
            uu = xa*w(i, j, k, ivx) + ya*w(i, j, k, ivy) + za*w(i, j, k&
&             , ivz) - qs
            um = zero
            up = zero
            if (uu .lt. zero) um = uu
            if (uu .gt. zero) up = uu
            bb(1, k) = bb(1, k) - up
            dd(1, k) = dd(1, k) + um
            bb(2, k) = bb(2, k) - up
            dd(2, k) = dd(2, k) + um
            rblank = real(iblank(i, j, k), realtype)
            cc(1, 1, k) = qq(i, j, k, 1, 1)
            cc(1, 2, k) = qq(i, j, k, 1, 2)*rblank
            cc(2, 1, k) = qq(i, j, k, 2, 1)*rblank
            cc(2, 2, k) = qq(i, j, k, 2, 2)
            ff(1, k) = scratch(i, j, k, idvt)*rblank
            ff(2, k) = scratch(i, j, k, idvt+1)*rblank
            bb(:, k) = bb(:, k)*rblank
            dd(:, k) = dd(:, k)*rblank
          end do
          call tdia2x2(2_inttype, kl, bb, cc, dd, ff)
          do k=2,kl
            scratch(i, j, k, idvt) = ff(1, k)
            scratch(i, j, k, idvt+1) = ff(2, k)
          end do
        end do
      end do
! ---------------- update (algorithm 2 damping on gam) ----------------
      factor = one
      if (turbrelax .eq. turbrelaxexplicit) factor = alfaturb
      ndampcapgamma = 0
      do k=2,kl
        do j=2,jl
          do i=2,il
            w(i, j, k, itu1) = w(i, j, k, itu1) + factor*scalenu*scratch&
&             (i, j, k, idvt)
            if (w(i, j, k, itu1) .lt. zero) then
              w(i, j, k, itu1) = zero
            else
              w(i, j, k, itu1) = w(i, j, k, itu1)
            end if
            gammadelta = factor*scalegamma*scratch(i, j, k, idvt+1)
            gammanew = w(i, j, k, itu2) + gammadelta
            dampfactor = one
            do mm=1,transitiondampmaxiter
              if (gammanew .ge. rsagrgammalo .and. gammanew .le. &
&                 rsagrgammahi) then
                goto 100
              else
                dampfactor = dampfactor*transitiondamptheta
                gammanew = w(i, j, k, itu2) + dampfactor*gammadelta
              end if
            end do
 100        if (gammanew .lt. rsagrgammalo .or. gammanew .gt. &
&               rsagrgammahi) then
              ndampcapgamma = ndampcapgamma + 1
              if (gammanew .lt. rsagrgammalo) then
                x3 = rsagrgammalo
              else
                x3 = gammanew
              end if
              if (x3 .gt. rsagrgammahi) then
                gammanew = rsagrgammahi
              else
                gammanew = x3
              end if
            end if
            w(i, j, k, itu2) = gammanew
          end do
        end do
      end do
      if (ndampcapgamma .gt. 0) print*, &
&  'warning: sa-sgamma update damping exhausted transitiondampmaxiter ('&
&                               , transitiondampmaxiter, ') in ', &
&                               ndampcapgamma, &
&                               ' gam cells; values clipped.'
    end if
  end subroutine sagammasolve

  subroutine evalsrcjacblocksagamma(i, j, k, a)
!
! source jacobian a = ds/dq (2x2) for cell (i,j,k) by finite
! differences of cellsources. independent of qq. used by
! computesrclambdasagamma (p&z eq. 59).
!
    use blockpointers
    use constants
    use paramturb
    use inputphysics
    use flowvarrefstate
    use inputdiscretization, only : approxsa
    use inputiteration, only : transitionuseapproxsa, sgammavortlimiter,&
&   sgammaonsettanh, sgammafturblee, sgammacoupledestruction, &
&   sgammafpgsmoothp, sgammactu1, sgammactu2, sgammactu3
    implicit none
    integer(kind=inttype), intent(in) :: i, j, k
    real(kind=realtype), intent(out) :: a(2, 2)
    real(kind=realtype) :: ss, strainmag, vortmag, duds, velmag, vortlim
    real(kind=realtype) :: uux, uuy, uuz, vvx, vvy, vvz, wwx, wwy, wwz, &
&   fact
    real(kind=realtype) :: nu, dist2inv, chi, chi2, ft2, tupct, ydist, &
&   nutilde, gam
    real(kind=realtype) :: snu, sgamma, snup, sgamp, epsnu, epsg
    real(kind=realtype) :: d1, d2, d3, d4, d5, d6, d7, d8, d9, d10, d11&
&   , d12, d13, d14
    real(kind=realtype) :: d15, d16, d17, d18, d19, d20, d21, d22, d23, &
&   d24, d25, d26
    logical :: approxterm1
    intrinsic exp
    intrinsic abs
    intrinsic max
    real(kind=8) :: x1
    real(kind=realtype) :: abs0
    approxterm1 = approxsa .and. transitionuseapproxsa
    tupct = turbintensityinf*100.0_realtype
    call cellkinematics(i, j, k, ss, strainmag, vortmag, duds, velmag, &
&                 vortlim, uux, uuy, uuz, vvx, vvy, vvz, wwx, wwy, wwz, &
&                 fact)
    nu = rlv(i, j, k)/w(i, j, k, irho)
    dist2inv = one/d2wall(i, j, k)**2
    ydist = d2wall(i, j, k)
    nutilde = w(i, j, k, itu1)
    gam = w(i, j, k, itu2)
    chi = nutilde/nu
    chi2 = chi*chi
    if (useft2sa) then
      ft2 = rsact3*exp(-(rsact4*chi2))
    else
      ft2 = zero
    end if
    call cellsources(nutilde, gam, nu, dist2inv, ss, strainmag, vortmag&
&              , ydist, duds, w(i, j, k, irho), rlv(i, j, k), tupct, &
&              vortlim, ft2, approxterm1, sgammavortlimiter, &
&              sgammaonsettanh, sgammafturblee, sgammacoupledestruction&
&              , sgammafpgsmoothp, sgammactu1, sgammactu2, sgammactu3, &
&              snu, sgamma, d1, d2, d3, d4, d5, d6, d7, d8, d9, d10, d11&
&              , d12, d13, d14, d15, d16, d17, d18, d19, d20, d21, d22, &
&              d23, d24, d25, d26)
    if (nutilde .ge. 0.) then
      abs0 = nutilde
    else
      abs0 = -nutilde
    end if
    x1 = 1.0e-6_realtype*abs0
    if (x1 .lt. 1.0e-12_realtype*nu) then
      epsnu = 1.0e-12_realtype*nu
    else
      epsnu = x1
    end if
    epsg = 1.0e-6_realtype
    call cellsources(nutilde + epsnu, gam, nu, dist2inv, ss, strainmag, &
&              vortmag, ydist, duds, w(i, j, k, irho), rlv(i, j, k), &
&              tupct, vortlim, ft2, approxterm1, sgammavortlimiter, &
&              sgammaonsettanh, sgammafturblee, sgammacoupledestruction&
&              , sgammafpgsmoothp, sgammactu1, sgammactu2, sgammactu3, &
&              snup, sgamp, d1, d2, d3, d4, d5, d6, d7, d8, d9, d10, d11&
&              , d12, d13, d14, d15, d16, d17, d18, d19, d20, d21, d22, &
&              d23, d24, d25, d26)
    a(1, 1) = (snup-snu)/epsnu
    a(2, 1) = (sgamp-sgamma)/epsnu
    call cellsources(nutilde, gam + epsg, nu, dist2inv, ss, strainmag, &
&              vortmag, ydist, duds, w(i, j, k, irho), rlv(i, j, k), &
&              tupct, vortlim, ft2, approxterm1, sgammavortlimiter, &
&              sgammaonsettanh, sgammafturblee, sgammacoupledestruction&
&              , sgammafpgsmoothp, sgammactu1, sgammactu2, sgammactu3, &
&              snup, sgamp, d1, d2, d3, d4, d5, d6, d7, d8, d9, d10, d11&
&              , d12, d13, d14, d15, d16, d17, d18, d19, d20, d21, d22, &
&              d23, d24, d25, d26)
    a(1, 2) = (snup-snu)/epsg
    a(2, 2) = (sgamp-sgamma)/epsg
  end subroutine evalsrcjacblocksagamma

  subroutine computesrclambdasagamma(mode)
!
! srclambda(i,j,k,1:2) for the sa-sgamma 2x2 source jacobian (p&z eq. 59).
! same modes as sagammaretheta%computesrclambda; srclambda(:,:,:,3)
! (allocated for both models) is set to zero and never read for nwt=2.
!
    use constants
    use blockpointers, only : il, jl, kl, srclambda
    use paramturb, only : srclambdamodedecoupled
    implicit none
    integer(kind=inttype), intent(in) :: mode
    integer(kind=inttype) :: i, j, k
    real(kind=realtype) :: a(2, 2), tr2, disc2, lambda2x2
    intrinsic max
    intrinsic sqrt
    real(kind=realtype) :: result1
    do k=2,kl
      do j=2,jl
        do i=2,il
          call evalsrcjacblocksagamma(i, j, k, a)
          if (mode .eq. srclambdamodedecoupled) then
            if (zero .lt. a(1, 1)) then
              srclambda(i, j, k, 1) = a(1, 1)
            else
              srclambda(i, j, k, 1) = zero
            end if
            if (zero .lt. a(2, 2)) then
              srclambda(i, j, k, 2) = a(2, 2)
            else
              srclambda(i, j, k, 2) = zero
            end if
          else
            tr2 = a(1, 1) + a(2, 2)
            disc2 = ((a(1, 1)-a(2, 2))*half)**2 + a(1, 2)*a(2, 1)
            if (disc2 .ge. zero) then
              result1 = sqrt(disc2)
              lambda2x2 = tr2*half + result1
            else
              lambda2x2 = tr2*half
            end if
            if (zero .lt. lambda2x2) then
              lambda2x2 = lambda2x2
            else
              lambda2x2 = zero
            end if
            srclambda(i, j, k, 1) = lambda2x2
            srclambda(i, j, k, 2) = lambda2x2
          end if
          srclambda(i, j, k, 3) = zero
        end do
      end do
    end do
  end subroutine computesrclambdasagamma

