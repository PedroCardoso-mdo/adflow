        if (branch .eq. 0) then
          chi2d = -(rsact4*exp(-(rsact4*chi2))*rsact3*ft2d)
        else
          chi2d = 0.0_8
        end if
        temp = d2wall(i, j, k)
        chid = 2*chi*chi2d
        nutilded = nutilded + chid/nu
        nud = nud - nutilde*chid/nu**2
        wd(i, j, k, itu2) = wd(i, j, k, itu2) + gamd
        wd(i, j, k, itu1) = wd(i, j, k, itu1) + nutilded
        d2walld(i, j, k) = d2walld(i, j, k) + ydistd - 2*one*dist2invd/&
&         temp**3
        temp = w(i, j, k, irho)
        rlvd(i, j, k) = rlvd(i, j, k) + nud/temp
        wd(i, j, k, irho) = wd(i, j, k, irho) - rlv(i, j, k)*nud/temp**2
        call cellkinematics_b(i, j, k, ss, ssd, strainmag, strainmagd, &
&                       vortmag, vortmagd, duds, dudsd, velmag, vortlim&
&                       , vortlimd, uux, uuy, uuz, vvx, vvy, vvz, wwx, &
&                       wwy, wwz, fact)
      end do
    end if
