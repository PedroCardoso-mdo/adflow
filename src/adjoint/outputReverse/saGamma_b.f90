      temp = w(i, j, k+1, irho)
      rlvd(i, j, k+1) = rlvd(i, j, k+1) + nu_pd/temp
      wd(i, j, k+1, irho) = wd(i, j, k+1, irho) - rlv(i, j, k+1)*nu_pd/&
