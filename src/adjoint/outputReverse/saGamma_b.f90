    if (temp .le. 0.0_8 .and. (sixth .eq. 0.0_8 .or. sixth .ne. int(&
&       sixth))) then
      gg6d = 0.0_8
    else
      gg6d = -(temp*sixth*temp**(sixth-1)*termfwd/(cw36+gg6))
    end if
    arg1d1 = 0.0_8
    gs0d = 0.0_8
    call smoothminmax_b(gs0, gs0d, arg11, arg1d1, rsagrpmax, gammasd)
    gclip1d = gs0d/(one-one/rsagrce2)
    arg1d0 = 0.0_8
    call smoothminmax_b(gam, gamd, arg10, arg1d0, rsagrpmin, gclip1d)
    ggd = termfw*fwsad + 6*gg**5*gg6d
    rrd = (6*rr**5*rsacw2-rsacw2+1.0)*ggd
    call popcontrol1b(branch)
    if (branch .eq. 0) rrd = 0.0_8
    tempd0 = kar2inv*rrd/sst
    nutilded = nutilded + dist2inv*tempd0
    dist2invd = dist2invd + nutilde*tempd0
    sstd = -(nutilde*dist2inv*tempd0/sst)
    call popcontrol1b(branch)
    if (branch .eq. 0) sstd = 0.0_8
    ssd = ssd + sstd
    tempd0 = kar2inv*sstd
    nutilded = nutilded + fv2*dist2inv*tempd0
    fv2d = fv2d + nutilde*dist2inv*tempd0
    dist2invd = dist2invd + nutilde*fv2*tempd0
    tempd = -(fv2d/(one+chi*fv1))
    chid = tempd
    tempd0 = -(chi*tempd/(one+chi*fv1))
    fv1d = fv1d + chi*tempd0
    tempd = fv1d/(cv13+chi3)
    chi3d = (1.0-chi3/(cv13+chi3))*tempd
    chi2d = chi*chi3d
    chid = chid + fv1*tempd0 + chi2*chi3d + 2*chi*chi2d
    nutilded = nutilded + chid/nu
    nud = nud - nutilde*chid/nu**2
  end subroutine cellsources_b

  subroutine cellsources(nutilde, gam, nu, dist2inv, ss, strainmag, &
&   vortmag, ydist, duds, rho, mu, tupct, vortlim, ft2, approxterm1, &
&   uselimiter, onsettanh, fturblee, coupledest, psmooth, ctu1, ctu2, &
&   ctu3, snu, sgamma, gammas, destmult, term2prod, term2dest, fv1, fv2&
&   , sst, rr, gg, gg6, termfw, fwsa, revort, laml, fpg, rethetac, &
&   fonset1, fonset, fturb, pgamma, egamma, gammalocal, seff, omeff, &
&   rturb, nutsa)
!
! per-cell sa and gam sources of sa-sgamma from the state
! (nutilde, gam) and the cell kinematics. used by source (residual,
! differentiated) and, under #ifndef 1, for the finite-
! difference lhs jacobian and by evalsrcjacblocksagamma (eq. 59).
! every smoothminmax has its own target variable (no in-place
! update on the differentiated path -- fast-reverse rule).
!
    use constants
    use paramturb, only : rsacv1, rsak, rsacw3, rsacb1, rsacw1, rsacw2, &
&   rsact3, rsact4, rsagrca2, rsagrce2, rsagrgammalo, rsagrgammahi, &
&   rsagrpmin, rsagrpmax
    use turbutils_b, only : smoothminmax
    implicit none
    real(kind=realtype), intent(in) :: nutilde, gam, nu, dist2inv, ss, &
&   strainmag, vortmag
    real(kind=realtype), intent(in) :: ydist, duds, rho, mu, tupct, &
&   vortlim, ft2
    logical, intent(in) :: approxterm1, uselimiter, onsettanh, fturblee&
&   , coupledest
    real(kind=realtype), intent(in) :: psmooth, ctu1, ctu2, ctu3
    real(kind=realtype), intent(out) :: snu, sgamma, gammas, destmult, &
&   term2prod, term2dest
    real(kind=realtype), intent(out) :: fv1, fv2, sst, rr, gg, gg6, &
&   termfw, fwsa
    real(kind=realtype), intent(out) :: revort, laml, fpg, rethetac, &
&   fonset1, fonset, fturb
    real(kind=realtype), intent(out) :: pgamma, egamma, gammalocal, seff&
&   , omeff, rturb, nutsa
    real(kind=realtype), parameter :: xminn=1.e-10_realtype
    real(kind=realtype) :: cv13, kar2inv, cw36, chi, chi2, chi3
    real(kind=realtype) :: term1, term2
    real(kind=realtype) :: gclip1, gs0, lamraw, lamlo, lamplus, lamminus
    real(kind=realtype) :: fpgplusraw, fpgplus, fpgminusraw, fpgminus
    real(kind=realtype) :: fonset2, fonset3raw, fonset3, fonsetraw, &
&   fonset1t
    intrinsic max
    intrinsic min
    intrinsic exp
    intrinsic sqrt
    intrinsic tanh
    real(kind=realtype) :: x1
    real(kind=realtype) :: arg1
    cv13 = rsacv1**3
    kar2inv = one/rsak**2
    cw36 = rsacw3**6
! ---------------- sa part (lockstep sagammaretheta.f90 source) ----------------
    chi = nutilde/nu
    chi2 = chi*chi
    chi3 = chi*chi2
    fv1 = chi3/(chi3+cv13)
    fv2 = one - chi/(one+chi*fv1)
    sst = ss + nutilde*fv2*kar2inv*dist2inv
    if (sst .lt. xminn) then
      sst = xminn
    else
      sst = sst
    end if
    rr = nutilde*kar2inv*dist2inv/sst
    if (rr .gt. 10.0_realtype) then
      rr = 10.0_realtype
    else
      rr = rr
    end if
    gg = rr + rsacw2*(rr**6-rr)
    gg6 = gg**6
    termfw = ((one+cw36)/(gg6+cw36))**sixth
    fwsa = gg*termfw
! eq. 10: rescaled intermittency gamma_s (nichols/lee 3.18), smooth
    gclip1 = smoothminmax(gam, one, rsagrpmin)
    gs0 = (gclip1-one/rsagrce2)/(one-one/rsagrce2)
    gammas = smoothminmax(gs0, zero, rsagrpmax)
    if (coupledest) then
      destmult = smoothminmax(gammas, sgdestfloor, rsagrpmax)
    else
      destmult = one
    end if
    if (approxterm1) then
      term1 = zero
    else
      term1 = gammas*rsacb1*(one-ft2)*ss
    end if
    term2prod = dist2inv*kar2inv*rsacb1*((one-ft2)*fv2+ft2)
    term2dest = -(dist2inv*rsacw1*fwsa)
    term2 = gammas*term2prod + destmult*term2dest
    snu = (term1+term2*nutilde)*nutilde
! ---------------- gam part ----------------
    nutsa = nutilde*fv1
    rturb = nutsa/nu
    if (gam .lt. rsagrgammalo) then
      x1 = rsagrgammalo
    else
      x1 = gam
    end if
    if (x1 .gt. rsagrgammahi) then
      gammalocal = rsagrgammahi
    else
      gammalocal = x1
    end if
! eq. 8: local pressure-gradient parameter (continuity form), smooth clip [-1, 1]
    lamraw = sglamcoef*ydist**2/nu*duds + sglamoffset
    lamlo = smoothminmax(lamraw, -sglamclip, rsagrpmax)
    laml = smoothminmax(lamlo, sglamclip, rsagrpmin)
! eq. 7: f_pg (v with caps) and re_theta_c
    lamplus = smoothminmax(laml, zero, psmooth)
    lamminus = smoothminmax(laml, zero, -psmooth)
    fpgplusraw = sgcpg1*lamplus
    arg1 = sgcpg1lim - one
    fpgplus = smoothminmax(fpgplusraw, arg1, -psmooth)
    fpgminusraw = sgcpg2*lamminus
    arg1 = sgcpg2lim - one
    fpgminus = smoothminmax(fpgminusraw, arg1, -psmooth)
    fpg = one + fpgplus + fpgminus
    rethetac = ctu1 + ctu2*exp(-(ctu3*tupct*fpg))
! eq. 4: onset
    revort = rho*ydist**2*strainmag/mu
    if (onsettanh) then
      fonset1t = sqrt((revort/(sgfonsetc*rethetac))**2 + rturb**2)
      fonset1 = fonset1t
      fonset = (tanh(sgtanhk*(fonset1t-sgtanhs))+one)*half
    else
      fonset1 = revort/(sgfonsetc*rethetac)
      fonset2 = smoothminmax(fonset1, two, rsagrpmin)
      fonset3raw = one - (rturb/sgfonsetrt)**3
      fonset3 = smoothminmax(fonset3raw, zero, rsagrpmax)
      fonsetraw = fonset2 - fonset3
      fonset = smoothminmax(fonsetraw, zero, rsagrpmax)
    end if
! eq. 5: f_turb
    if (fturblee) then
      fturb = exp(-((rturb/two)**4))
    else
      fturb = (one-fonset)*exp(-rturb)
    end if
! eqs. 2-3: production with s, destruction with omega (optional p&z floor)
    if (uselimiter) then
      seff = smoothminmax(strainmag, vortlim, rsagrpmin)
      omeff = smoothminmax(vortmag, vortlim, rsagrpmin)
    else
      seff = strainmag
      omeff = vortmag
    end if
    pgamma = sgflength*seff*gammalocal*(one-gammalocal)*fonset
    egamma = rsagrca2*omeff*gammalocal*fturb*(rsagrce2*gammalocal-one)
    sgamma = pgamma - egamma
  end subroutine cellsources

!  differentiation of cellkinematics in reverse (adjoint) mode (with options noisize i4 dr8 r8):
!   gradient     of useful results: timeref muinf uinf *w *vol
!                *si *sj *sk vortlim vortmag duds strainmag ss
!   with respect to varying inputs: timeref muinf uinf *w *vol
!                *si *sj *sk
!   plus diff mem management of: w:in vol:in si:in sj:in sk:in
  subroutine cellkinematics_b(i, j, k, ss, ssd, strainmag, strainmagd, &
&   vortmag, vortmagd, duds, dudsd, velmag, vortlim, vortlimd, uux, uuy&
&   , uuz, vvx, vvy, vvz, wwx, wwy, wwz, fact)
!
! cell-centre velocity gradients, sa production magnitude ss (strain or
! vorticity per turbprod), strain and vorticity magnitudes, streamwise
! velocity gradient du/ds (relative frame) and the p&z vorticity-limiter
! threshold. lockstep sagammaretheta.f90 source (gradient + rotating-
! frame blocks), minus everything that needs rethetatilde.
!
    use blockpointers
    use constants
    use section
    use inputphysics
    use flowvarrefstate
    use inputiteration, only : transitionreflength
    implicit none
    integer(kind=inttype), intent(in) :: i, j, k
    real(kind=realtype) :: ss, strainmag, vortmag, duds, velmag, vortlim
    real(kind=realtype) :: ssd, strainmagd, vortmagd, dudsd, vortlimd
    real(kind=realtype) :: uux, uuy, uuz, vvx, vvy, vvz, wwx, wwy, wwz, &
&   fact
    real(kind=realtype) :: uuxd
    real(kind=realtype), parameter :: f23=two*third
    real(kind=realtype), parameter :: xminn=1.e-10_realtype
    real(kind=realtype) :: div2, sxx, syy, szz, sxy, sxz, syz
    real(kind=realtype) :: div2d, sxxd, syyd, szzd, sxyd, sxzd, syzd
    real(kind=realtype) :: vortx, vorty, vortz, omegax, omegay, omegaz
    real(kind=realtype) :: vortxd, vortyd, vortzd, omegaxd, omegayd, &
&   omegazd
    real(kind=realtype) :: strainmag2, strainprod, vortprod
    real(kind=realtype) :: strainmag2d, strainprodd, vortprodd
    real(kind=realtype) :: xc(3), xxc(3), sc(3)
    real(kind=realtype) :: scd(3)
    real(kind=realtype) :: velrelx, velrely, velrelz, velmag2, ureftrans&
&   , reflentrans
    real(kind=realtype) :: velrelxd, velrelyd, velrelzd, velmag2d, &
&   ureftransd
    real(kind=realtype) :: uxhat, uyhat, uzhat
    real(kind=realtype) :: uxhatd, uyhatd, uzhatd
    intrinsic sqrt
    intrinsic max
    real(kind=realtype) :: x1
    real(kind=realtype) :: x1d
    real(kind=realtype) :: max1
    real(kind=realtype) :: max1d
    real(kind=realtype) :: max2
    real(kind=realtype) :: max2d
    real(kind=realtype) :: max3
    real(kind=realtype) :: max3d
    real(kind=realtype) :: max4
    real(kind=realtype) :: max4d
    real(kind=realtype) :: max5
    real(kind=realtype) :: max5d
    real(kind=realtype) :: max6
    real(kind=realtype) :: max6d
    real(kind=realtype) :: max7
    real(kind=realtype) :: max7d
    real(kind=realtype) :: max8
    real(kind=realtype) :: max8d
    real(kind=realtype) :: velmagd
    real(kind=realtype) :: uuyd
    real(kind=realtype) :: uuzd
    real(kind=realtype) :: vvxd
    real(kind=realtype) :: vvyd
    real(kind=realtype) :: vvzd
    real(kind=realtype) :: wwxd
    real(kind=realtype) :: wwyd
    real(kind=realtype) :: wwzd
    real(kind=realtype) :: factd
    real(kind=realtype) :: temp
    real(kind=realtype) :: tempd
    real(kind=realtype) :: temp0
    real(kind=realtype) :: temp1
    real(kind=realtype) :: temp2
    real(kind=realtype) :: tempd0
    real(kind=realtype) :: tempd1
    real(kind=realtype) :: tempd2
    integer :: branch
    omegax = timeref*sections(sectionid)%rotrate(1)
    omegay = timeref*sections(sectionid)%rotrate(2)
    omegaz = timeref*sections(sectionid)%rotrate(3)
    uux = w(i+1, j, k, ivx)*si(i, j, k, 1) - w(i-1, j, k, ivx)*si(i-1, j&
&     , k, 1) + w(i, j+1, k, ivx)*sj(i, j, k, 1) - w(i, j-1, k, ivx)*sj(&
&     i, j-1, k, 1) + w(i, j, k+1, ivx)*sk(i, j, k, 1) - w(i, j, k-1, &
&     ivx)*sk(i, j, k-1, 1)
    uuy = w(i+1, j, k, ivx)*si(i, j, k, 2) - w(i-1, j, k, ivx)*si(i-1, j&
&     , k, 2) + w(i, j+1, k, ivx)*sj(i, j, k, 2) - w(i, j-1, k, ivx)*sj(&
&     i, j-1, k, 2) + w(i, j, k+1, ivx)*sk(i, j, k, 2) - w(i, j, k-1, &
&     ivx)*sk(i, j, k-1, 2)
    uuz = w(i+1, j, k, ivx)*si(i, j, k, 3) - w(i-1, j, k, ivx)*si(i-1, j&
&     , k, 3) + w(i, j+1, k, ivx)*sj(i, j, k, 3) - w(i, j-1, k, ivx)*sj(&
&     i, j-1, k, 3) + w(i, j, k+1, ivx)*sk(i, j, k, 3) - w(i, j, k-1, &
&     ivx)*sk(i, j, k-1, 3)
    vvx = w(i+1, j, k, ivy)*si(i, j, k, 1) - w(i-1, j, k, ivy)*si(i-1, j&
&     , k, 1) + w(i, j+1, k, ivy)*sj(i, j, k, 1) - w(i, j-1, k, ivy)*sj(&
&     i, j-1, k, 1) + w(i, j, k+1, ivy)*sk(i, j, k, 1) - w(i, j, k-1, &
&     ivy)*sk(i, j, k-1, 1)
    vvy = w(i+1, j, k, ivy)*si(i, j, k, 2) - w(i-1, j, k, ivy)*si(i-1, j&
&     , k, 2) + w(i, j+1, k, ivy)*sj(i, j, k, 2) - w(i, j-1, k, ivy)*sj(&
&     i, j-1, k, 2) + w(i, j, k+1, ivy)*sk(i, j, k, 2) - w(i, j, k-1, &
&     ivy)*sk(i, j, k-1, 2)
    vvz = w(i+1, j, k, ivy)*si(i, j, k, 3) - w(i-1, j, k, ivy)*si(i-1, j&
&     , k, 3) + w(i, j+1, k, ivy)*sj(i, j, k, 3) - w(i, j-1, k, ivy)*sj(&
&     i, j-1, k, 3) + w(i, j, k+1, ivy)*sk(i, j, k, 3) - w(i, j, k-1, &
&     ivy)*sk(i, j, k-1, 3)
    wwx = w(i+1, j, k, ivz)*si(i, j, k, 1) - w(i-1, j, k, ivz)*si(i-1, j&
&     , k, 1) + w(i, j+1, k, ivz)*sj(i, j, k, 1) - w(i, j-1, k, ivz)*sj(&
&     i, j-1, k, 1) + w(i, j, k+1, ivz)*sk(i, j, k, 1) - w(i, j, k-1, &
&     ivz)*sk(i, j, k-1, 1)
    wwy = w(i+1, j, k, ivz)*si(i, j, k, 2) - w(i-1, j, k, ivz)*si(i-1, j&
&     , k, 2) + w(i, j+1, k, ivz)*sj(i, j, k, 2) - w(i, j-1, k, ivz)*sj(&
&     i, j-1, k, 2) + w(i, j, k+1, ivz)*sk(i, j, k, 2) - w(i, j, k-1, &
&     ivz)*sk(i, j, k-1, 2)
    wwz = w(i+1, j, k, ivz)*si(i, j, k, 3) - w(i-1, j, k, ivz)*si(i-1, j&
&     , k, 3) + w(i, j+1, k, ivz)*sj(i, j, k, 3) - w(i, j-1, k, ivz)*sj(&
&     i, j-1, k, 3) + w(i, j, k+1, ivz)*sk(i, j, k, 3) - w(i, j, k-1, &
&     ivz)*sk(i, j, k-1, 3)
    fact = fourth/vol(i, j, k)
    sxx = two*fact*uux
    syy = two*fact*vvy
    szz = two*fact*wwz
    sxy = fact*(uuy+vvx)
    sxz = fact*(uuz+wwx)
    syz = fact*(vvz+wwy)
    strainmag2 = two*(sxy**2+sxz**2+syz**2) + sxx**2 + syy**2 + szz**2
    vortx = two*fact*(wwy-vvz) - two*omegax
    vorty = two*fact*(uuz-wwx) - two*omegay
    vortz = two*fact*(vvx-uuy) - two*omegaz
    vortprod = vortx**2 + vorty**2 + vortz**2
! sa production magnitude per turbprod (strain or vorticity), as sa.f90
    if (turbprod .eq. strain) then
      div2 = f23*(sxx+syy+szz)**2
      strainprod = two*strainmag2 - div2
      call pushcontrol1b(1)
    else
      call pushcontrol1b(0)
    end if
    if (vortprod .lt. xminn) then
      max1 = xminn
      call pushcontrol1b(0)
    else
      max1 = vortprod
      call pushcontrol1b(1)
    end if
    if (two*strainmag2 .lt. xminn) then
      max2 = xminn
      call pushcontrol1b(0)
    else
      max2 = two*strainmag2
      call pushcontrol1b(1)
    end if
! relative (rotating-frame) velocity and streamwise gradient du/ds
    xc(1) = eighth*(x(i-1, j-1, k-1, 1)+x(i, j-1, k-1, 1)+x(i-1, j, k-1&
&     , 1)+x(i, j, k-1, 1)+x(i-1, j-1, k, 1)+x(i, j-1, k, 1)+x(i-1, j, k&
&     , 1)+x(i, j, k, 1))
    xc(2) = eighth*(x(i-1, j-1, k-1, 2)+x(i, j-1, k-1, 2)+x(i-1, j, k-1&
&     , 2)+x(i, j, k-1, 2)+x(i-1, j-1, k, 2)+x(i, j-1, k, 2)+x(i-1, j, k&
&     , 2)+x(i, j, k, 2))
    xc(3) = eighth*(x(i-1, j-1, k-1, 3)+x(i, j-1, k-1, 3)+x(i-1, j, k-1&
&     , 3)+x(i, j, k-1, 3)+x(i-1, j-1, k, 3)+x(i, j-1, k, 3)+x(i-1, j, k&
&     , 3)+x(i, j, k, 3))
    xxc(1) = xc(1) - sections(sectionid)%rotcenter(1)
    xxc(2) = xc(2) - sections(sectionid)%rotcenter(2)
    xxc(3) = xc(3) - sections(sectionid)%rotcenter(3)
    sc(1) = omegay*xxc(3) - omegaz*xxc(2)
    sc(2) = omegaz*xxc(1) - omegax*xxc(3)
    sc(3) = omegax*xxc(2) - omegay*xxc(1)
    velrelx = w(i, j, k, ivx) - sc(1)
    velrely = w(i, j, k, ivy) - sc(2)
    velrelz = w(i, j, k, ivz) - sc(3)
    velmag2 = velrelx**2 + velrely**2 + velrelz**2
    if (velmag2 .lt. xminn) then
      max3 = xminn
      call pushcontrol1b(0)
    else
      max3 = velmag2
      call pushcontrol1b(1)
    end if
    velmag = sqrt(max3)
    if (velmag .lt. xminn) then
      call pushcontrol1b(0)
      max4 = xminn
    else
      max4 = velmag
      call pushcontrol1b(1)
    end if
    uxhat = velrelx/max4
    if (velmag .lt. xminn) then
      call pushcontrol1b(0)
      max5 = xminn
    else
      max5 = velmag
      call pushcontrol1b(1)
    end if
    uyhat = velrely/max5
    if (velmag .lt. xminn) then
      max6 = xminn
      call pushcontrol1b(0)
    else
      max6 = velmag
      call pushcontrol1b(1)
    end if
    uzhat = velrelz/max6
! p&z vorticity-limiter threshold (eqs. 52-53), only used with sgammavortlimiter
    if (transitionreflength .gt. zero) then
      reflentrans = transitionreflength
    else
      reflentrans = lengthref
    end if
    ureftrans = sqrt(uinf**2 + sc(1)**2 + sc(2)**2 + sc(3)**2)
    if (muinf*reflentrans .lt. xminn) then
      call pushcontrol1b(0)
      max8 = xminn
    else
      max8 = muinf*reflentrans
      call pushcontrol1b(1)
    end if
    x1 = ureftrans/max8
    if (x1 .lt. xminn) then
      max7 = xminn
      call pushcontrol1b(0)
    else
      max7 = x1
      call pushcontrol1b(1)
    end if
    temp2 = sqrt(max7)
    ureftransd = temp2*vortlimd/20.0_realtype
    if (max7 .eq. 0.0_8) then
      max7d = 0.0_8
    else
      max7d = ureftrans*vortlimd/(2.0*temp2*20.0_realtype)
    end if
    call popcontrol1b(branch)
    if (branch .eq. 0) then
      x1d = 0.0_8
    else
      x1d = max7d
    end if
    ureftransd = ureftransd + x1d/max8
    max8d = -(ureftrans*x1d/max8**2)
    call popcontrol1b(branch)
    if (branch .ne. 0) muinfd = muinfd + reflentrans*max8d
    scd = 0.0_8
    if (uinf**2 + sc(1)**2 + sc(2)**2 + sc(3)**2 .eq. 0.0_8) then
      tempd0 = 0.0_8
    else
      tempd0 = ureftransd/(2.0*sqrt(uinf**2+sc(1)**2+sc(2)**2+sc(3)**2))
    end if
